//! Editor color themes (modeled on Notepad++'s stylers.model.xml and bundled themes).

use crate::highlight::St;
use crate::lang::Lang;

#[derive(Clone, Copy, Debug)]
pub struct TextStyle {
    pub fg: u32,
    pub bg: Option<u32>,
    pub bold: bool,
    pub italic: bool,
}

const fn s(fg: u32) -> TextStyle {
    TextStyle { fg, bg: None, bold: false, italic: false }
}
const fn b(fg: u32) -> TextStyle {
    TextStyle { fg, bg: None, bold: true, italic: false }
}
const fn it(fg: u32) -> TextStyle {
    TextStyle { fg, bg: None, bold: false, italic: true }
}
const fn sb(fg: u32, bg: u32, bold: bool) -> TextStyle {
    TextStyle { fg, bg: Some(bg), bold, italic: false }
}

