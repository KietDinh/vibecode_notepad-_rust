pub fn theme(i: usize) -> &'static Theme {
    &THEMES[i.min(THEMES.len() - 1)]
}

/// Resolve the text style of a token for a language in a theme.
pub fn style(t: &Theme, lang: Lang, st: St) -> TextStyle {
    let p = &t.pal;
    let def = s(t.fg);
    if !t.dark && t.name.starts_with("Default") {
        if let Some(x) = default_override(lang, st) {
            return x;
        }
    }
    match st {
        St::Default | St::Value => def,
        St::Comment | St::CommentLine => p.comment,
        St::CommentDoc => p.doc,
        St::Number => p.number,
        St::Keyword => p.keyword,
        St::Type => p.ty,
        St::Builtin => p.builtin,
        St::String | St::Char | St::Triple => p.string,
        St::Operator => p.operator,
        St::Preproc | St::Directive => p.preproc,
        St::FuncName | St::Macro => p.func,
        St::ClassName => TextStyle { bold: true, ..def },
        St::Decorator => TextStyle { italic: true, ..p.number },
        St::Lifetime => p.ty,
        St::Variable => p.var,
        St::Property => p.ty,
        St::Tag => p.tag,
        St::Attr => p.attr,
        St::AttrValue => p.value,
        St::Entity => TextStyle { italic: true, ..def },
        St::CData => p.number,
        St::XmlDecl => p.preproc,
        St::Sgml => p.doc,
        St::Text => def,
        St::Label => TextStyle { bold: true, ..p.attr },
        St::Section => TextStyle { bold: true, ..p.ty },
        St::Key => p.tag,
        St::Assign => p.operator,
        St::Heading => TextStyle { bold: true, ..p.keyword },
        St::Emph => TextStyle { italic: true, ..def },
        St::Strong => TextStyle { bold: true, ..def },
        St::Code => p.string,
        St::Link => p.func,
        St::Quote => p.comment,
        St::ListMark => p.number,
        St::DiffAdd => p.func,
        St::DiffDel => p.attr,
        St::DiffHeader => p.ty,
        St::DiffPos => p.number,
        St::DiffCmd => p.keyword,
        St::CssClass => p.attr,
        St::CssId => p.func,
        St::Pseudo => p.number,
        St::Important => TextStyle { bold: true, ..p.attr },
        St::SrHeader => TextStyle { bold: true, ..p.keyword },
        St::SrFile => TextStyle { bold: true, ..p.func },
        St::SrLine => p.comment,
    }
}

/// Exact Notepad++ default colors per language.
fn default_override(lang: Lang, st: St) -> Option<TextStyle> {
    use Lang::*;
    let r = match (lang, st) {
        (Python, St::Number) => s(0xFF0000),
        (Python, St::Triple) => s(0xFF8000),
        (Python, St::FuncName) => s(0xFF00FF),
        (Python, St::ClassName) => b(0x000000),
        (Python, St::Builtin) => b(0x880088),
        (Python, St::Decorator) => it(0xFF8000),
        (Rust, St::Comment | St::CommentLine) => s(0x007F00),
        (Rust, St::CommentDoc) => s(0x3F703F),
        (Rust, St::Number) => s(0x007F7F),
        (Rust, St::Keyword | St::Type) => b(0x00007F),
        (Rust, St::String | St::Char) => s(0x7F007F),
        (Rust, St::Operator) => b(0x000000),
        (Rust, St::Lifetime) => s(0x007F7F),
        (Rust, St::Macro) => s(0x7F7F00),
        (Json, St::String) => s(0x800000),
        (Json, St::Property) => s(0x8000FF),
        (Json, St::Operator) => s(0x000000),
        (Json, St::Keyword) => b(0x18AF8A),
        (Html | Xml, St::Text) => b(0x000000),
        (Html | Xml, St::Number) => s(0xFF0000),
        (Html | Xml, St::AttrValue) => b(0x8000FF),
        (Html | Xml, St::Tag) => s(0x0000FF),
        (Html | Xml, St::Attr) => s(0xFF0000),
        (Html | Xml, St::CData) => s(0xFF8000),
        (Html | Xml, St::Sgml) => sb(0x000000, 0xA6CAF0, false),
        (Html | Xml, St::Entity) => TextStyle { fg: 0x000000, bg: Some(0xFEFDE0), bold: false, italic: true },
        (Html | Xml, St::XmlDecl) => sb(0xFF0000, 0xFFFF00, false),
        (Batch, St::Keyword) => b(0x0000FF),
        (Batch, St::Label) => sb(0xFF0000, 0xFFFF80, true),
        (Batch, St::Variable) => sb(0xFF8000, 0xFCFFF0, true),
        (Batch, St::Operator) => b(0xFF0000),
        (Shell, St::Number) => s(0xFF0000),
        (Shell, St::Operator) => b(0x804000),
        (Shell | Perl | Makefile | CMake, St::Variable) => sb(0xFF8040, 0xFFFFD9, true),
        (Ini | Properties | Toml, St::Section) => sb(0x8000FF, 0xF2F4FF, true),
        (Ini | Properties | Toml, St::Assign) => b(0xFF0000),
        (Ini | Properties | Toml, St::Key) => it(0x0000FF),
        (Sql, St::Type) => s(0x800080),
        (Css, St::Tag) => s(0x0000FF),
        (Css, St::CssClass) => s(0xFF0000),
        (Css, St::CssId) => b(0x0080FF),
        (Css, St::Pseudo) => b(0xFF8000),
        (Css, St::Property) => b(0x8080C0),
        (Css, St::Value) => b(0x000000),
        (Css, St::Operator) => b(0x000000),
        (Css, St::Directive) => s(0x0080FF),
        (Css, St::Important) => b(0xFF0000),
        (PowerShell, St::Variable) => b(0x000000),
        (PowerShell, St::Type) => s(0x8000FF),
        (Php, St::Variable) => s(0x000080),
        (Yaml, St::Key) => b(0x000080),
        (Yaml, St::Number) => s(0xFF8040),
        (Yaml, St::Variable) => s(0x804000),
        (Yaml, St::Directive) => s(0x0000FF),
        (Yaml, St::Operator) => s(0x000000),
        (Diff, St::DiffCmd) => b(0x0000FF),
        (Diff, St::DiffHeader) => s(0x8000FF),
        (Diff, St::DiffPos) => s(0xFF8000),
        (Diff, St::DiffDel) => s(0x808040),
        (Diff, St::DiffAdd) => s(0x0080FF),
        (Lua, St::Builtin) => b(0x0080C0),
        (Makefile, St::Keyword) => sb(0x000080, 0xC0C0C0, true),
        (Markdown, St::Heading) => b(0x000080),
        (Markdown, St::Code) => sb(0x804000, 0xF4F4F4, false),
        (Markdown, St::Link) => s(0x0000FF),
        (Markdown, St::Quote) => it(0x008000),
        (Markdown, St::ListMark) => b(0xFF8000),
        (Markdown, St::Emph) => it(0x000000),
        (Markdown, St::Strong) => b(0x000000),
        (SearchResult, St::SrHeader) => sb(0x000080, 0xBBBBFF, true),
        (SearchResult, St::SrFile) => sb(0x008000, 0xFFFFBF, true),
        (SearchResult, St::SrLine) => s(0x808080),
        (Tex, St::Variable) => b(0x0000FF),
        _ => return None,
    };
    Some(r)
}
